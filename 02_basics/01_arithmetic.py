# ==================== Arithmetic & Augmented Assignment Operators ====================

"""
Arithmetic Operators Overview:
- Standard arithmetic operators calculate mathematical operations between operands.
- Augmented Assignment (In-Place / Shortcut Operators):
  Combines an arithmetic operation with assignment (e.g., x += 1 is equivalent to x = x + 1).
- Division Note: In Python 3, standard division (/) always returns a float.
"""

friends = 10

# ==================== 1. Addition ====================
# Standard addition
# friends = friends + 1
# Augmented addition shortcut
# friends += 1

# ==================== 2. Subtraction ====================
# Standard subtraction
# friends = friends - 1
# Augmented subtraction shortcut
# friends -= 1

# ==================== 3. Multiplication ====================
# Standard multiplication
# friends = friends * 3
# Augmented multiplication shortcut
# friends *= 3

# ==================== 4. Division ====================
# Standard division (always returns float)
# friends = friends / 2
# Augmented division shortcut
# friends /= 2

# ==================== 5. Exponentiation (Power) ====================
# Standard exponentiation (10 raised to power 2)
# friends = friends ** 2
# Augmented exponentiation shortcut
# friends **= 2

# ==================== 6. Modulo (Remainder) ====================
# Modulo operator (%) returns the remainder of a division.
# remainder = friends % 2

