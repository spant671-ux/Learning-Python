#Arithmetic Operators
a = 7 
b = 4
c = a+b
print (c) # Output: 10

#Assignment Operators
a= 4-2 #Assigns the result of 4-2 to variable a
print (a) # Output: 2
b = 6 
b += 3 #Equivalent to b = b + 3, so b becomes 9
print (b) # Output: 9
b -= 3 #Equivalent to b = b - 3, so b becomes 6
print (b) # Output: 6

#Comparison Operators
d = 5<4 # Evaluates to False because 5 is not less than 4
print (d) # Output: False
d >= 5 # Evaluates to True because 5 is greater than or equal to 5
print (d) # Output: True
d !=5 # Evaluates to False because 5 is equal to 5
print (d) # Output: False
d == 5 # Evaluates to True because 5 is equal to 5
print (d) # Output: True

#Logical Operators
e = True or False # Evaluates to True because at least one operand is True
print (e) # Output: True

#Truth tables for logical operators:

# AND operator (and)
# A     B     A and B
# True  True  True
# True  False False
# False False False

# OR operator (or)
# A     B     A or B                
# True  True  True
# True  False True
# False False False

